// The site-wide service worker (super-app plan U7), served at /sw.js with
// scope "/". Generated at build time so the offline shell list comes from
// the tool registry rather than a hand-kept copy.
//
// Strategy (KTD5):
// - page navigations: network-first, falling back to the cached page, then
//   to the cached home page;
// - /_next/static, fonts, icons: cache-first (content-hashed, immutable);
// - /drive/api/* (live COE / car data): network-first with a cached copy
//   for offline;
// - /data/*.json (bundled reference data): stale-while-revalidate.
// Bump CACHE_VERSION to drop every older cache, including the old
// /etf-scoped "whatetf-v1" one.
import { TOOLS } from '@/lib/shared/tools'

export const dynamic = 'force-static'

const CACHE_VERSION = 'v2'

export function swSource() {
  const shell = ['/', ...TOOLS.flatMap((t) => [t.route, t.mathRoute])]
  return `// Generated by src/app/sw.js/route.js — do not edit by hand.
const CACHE_NAME = 'ndtm-${CACHE_VERSION}'
const SHELL_URLS = ${JSON.stringify(shell)}

self.addEventListener('install', (event) => {
  self.skipWaiting()
  event.waitUntil(
    caches.open(CACHE_NAME).then((cache) =>
      Promise.all(SHELL_URLS.map((url) => cache.add(url).catch(() => {})))
    )
  )
})

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE_NAME).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  )
})

function putCopy(request, response) {
  if (!response || !response.ok) return response
  const copy = response.clone()
  caches.open(CACHE_NAME).then((cache) => cache.put(request, copy))
  return response
}

self.addEventListener('fetch', (event) => {
  const { request } = event
  if (request.method !== 'GET') return
  const url = new URL(request.url)
  if (url.origin !== self.location.origin) return

  if (request.mode === 'navigate') {
    event.respondWith(
      fetch(request)
        .then((response) => putCopy(request, response))
        .catch(() => caches.match(request).then((cached) => cached || caches.match('/')))
    )
    return
  }

  if (url.pathname.startsWith('/drive/api/')) {
    event.respondWith(
      fetch(request)
        .then((response) => putCopy(request, response))
        .catch(() => caches.match(request))
    )
    return
  }

  if (url.pathname.startsWith('/data/')) {
    event.respondWith(
      caches.match(request).then((cached) => {
        const network = fetch(request).then((response) => putCopy(request, response)).catch(() => cached)
        return cached || network
      })
    )
    return
  }

  if (url.pathname.startsWith('/_next/static/') || url.pathname.startsWith('/icons/') || /\\.(svg|ico|png|woff2?)$/.test(url.pathname)) {
    event.respondWith(
      caches.match(request).then((cached) => cached || fetch(request).then((response) => putCopy(request, response)))
    )
  }
})
`
}

export function GET() {
  return new Response(swSource(), {
    headers: {
      'Content-Type': 'application/javascript; charset=utf-8',
      // Browsers re-check the worker script on navigation; never let a CDN
      // pin an old one.
      'Cache-Control': 'no-cache, no-store, must-revalidate',
    },
  })
}
